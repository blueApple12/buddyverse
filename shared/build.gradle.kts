// One version label for every platform (Settings/More footer): the Android versionName, the PC packageVersion and the
// git commit this build came from ("+" = built with uncommitted changes). Read from the files the ship step bumps.
fun gradleValue(file: String, key: String): String =
    Regex("""$key\s*=\s*"([^"]+)"""").find(rootProject.file(file).readText())?.groupValues?.get(1) ?: "?"
fun git(vararg args: String): String = runCatching {
    providers.exec { commandLine("git", "-C", rootDir.absolutePath, *args); isIgnoreExitValue = true }.standardOutput.asText.get().trim()
}.getOrDefault("")
val appVersionName = gradleValue("androidApp/build.gradle.kts", "versionName")
val appVersionPc = gradleValue("desktopApp/build.gradle.kts", "packageVersion")
val appVersionGit = git("rev-parse", "--short", "HEAD").ifBlank { "nogit" } +
    (if (git("status", "--porcelain", "--untracked-files=no").isNotBlank()) "+" else "")
val appVersion by tasks.registering {
    val out = layout.buildDirectory.dir("generated/appVersion/kotlin")
    inputs.property("name", appVersionName); inputs.property("pc", appVersionPc); inputs.property("git", appVersionGit)
    outputs.dir(out)
    doLast {
        val f = out.get().file("app/buddyverse/core/AppVersion.kt").asFile
        f.parentFile.mkdirs()
        f.writeText(
            "package app.buddyverse.core\n\n" +
                "/** Generated by :shared:appVersion (shared/build.gradle.kts). Same on phone, PC and web: compare them. */\n" +
                "object AppVersion {\n" +
                "    const val NAME = \"$appVersionName\"\n" +
                "    const val PC = \"$appVersionPc\"\n" +
                "    const val GIT = \"$appVersionGit\"\n" +
                "    const val LABEL = \"v$appVersionName Beta · PC $appVersionPc · $appVersionGit\"\n" +
                "}\n"
        )
    }
}

