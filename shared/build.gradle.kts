// The PWA packaged as a Hermes plugin (docs/web.md): build/hermes-plugin/buddyverse, copied to <HERMES_HOME>/plugins/buddyverse.
// The gateway serves plugin files only with browser-asset suffixes, so `*.wasm` ships as `*.wasm.json` (index.html compiles from bytes).
val webPlugin by tasks.registering(Sync::class) {
    inputs.property("version", "$appVersionName $appVersionPc $appVersionGit")
    into(layout.buildDirectory.dir("hermes-plugin/buddyverse"))
    from(rootProject.file("webPlugin"))
    from(tasks.named("wasmJsBrowserDistribution")) {
        into("dashboard")
        exclude("**/*.map")
        rename("""(.+)\.wasm""", "$1.wasm.json")
        filesMatching("buddyverse.js") { filter { it.replace(Regex("""([0-9a-f]{20})\.wasm\b"""), "$1.wasm.json") } }
        // Webpack bakes skiko's import.meta.url as this PC's build path; any file: URL behaves the same in a browser.
        filesMatching("buddyverse.js") { filter { it.replace("file:///" + rootDir.invariantSeparatorsPath, "file:///buddyverse/app") } }
    }
    // Shipped to other people's PCs: no trace of the build PC's folder (user name) may remain. Same-length patch for
    // any path the compiler still embedded (byte length is kept, so the wasm stays valid), then a hard check.
    doLast {
        // Per-build id for the service worker and the script URL (sw.js, index.html: `__BUILD__`): version + a hash of
        // the build's files, so each deploy that changes anything is a new sw.js, a new cache and a new buddyverse.js URL.
        val dash = destinationDir.resolve("dashboard")
        val md = MessageDigest.getInstance("SHA-256")
        dash.walkTopDown().filter { it.isFile }.sortedBy { it.path } // index.html, sw.js: still with `__BUILD__` here
            .forEach { md.update(it.relativeTo(dash).invariantSeparatorsPath.toByteArray()); md.update(it.readBytes()) }
        val build = "$appVersionName-" + md.digest().take(5).joinToString("") { "%02x".format(it) }
        for (n in listOf("index.html", "sw.js")) dash.resolve(n).let { it.writeText(it.readText().replace("__BUILD__", build)) }
        dash.resolve("build.json").writeText("{\"build\":\"$build\",\"version\":\"v$appVersionName · PC $appVersionPc\",\"git\":\"$appVersionGit\"}\n")
    }
    doLast {
        val needles = listOf(rootDir.invariantSeparatorsPath, rootDir.absolutePath).distinct().map { it.toByteArray() }
        destinationDir.walkTopDown().filter { it.isFile }.forEach { f ->
            val bytes = f.readBytes()
            var changed = false
            for (n in needles) {
                val pad = "/src".padEnd(n.size, '_').toByteArray()
                var i = indexOf(bytes, n, 0)
                while (i >= 0) { pad.copyInto(bytes, i); changed = true; i = indexOf(bytes, n, i + n.size) }
            }
            if (changed) f.writeBytes(bytes)
            val home = System.getProperty("user.home")
            val left = f.readBytes()
            for (h in listOf(home, home.replace('\\', '/'))) check(indexOf(left, h.toByteArray(), 0) < 0) { "build path left in ${f.name}" }
        }
    }
}

fun indexOf(hay: ByteArray, needle: ByteArray, from: Int): Int {
    outer@ for (i in from..hay.size - needle.size) {
        for (j in needle.indices) if (hay[i + j] != needle[j]) continue@outer
        return i
    }
    return -1
}
