# Fetches Material Symbols Rounded (weight 400 web set) and writes Icons.kt with their path data.
#   python tools/gen-icons.py
import re, sys, urllib.request, pathlib
NAMES = """add arrow_back arrow_upward stop mic close more_horiz search check check_circle error expand_more chevron_right
settings bolt smart_toy forum schedule apps play_arrow pause refresh content_copy delete edit push_pin archive unarchive
undo qr_code_scanner link attach_file image terminal description folder psychology extension build hub auto_awesome
insights monitor_heart group wifi_off power_settings_new language palette notifications vibration volume_up view_kanban
inventory_2 cable devices history lock help send dark_mode bug_report timer visibility chat lightbulb memory tune
favorite casino warning info logout add_comment keyboard_return reply sports_esports""".split()
out = []
root = pathlib.Path(__file__).resolve().parent.parent
for n in NAMES:
    for fill in ("", "_fill1"):
        url = f"https://raw.githubusercontent.com/google/material-design-icons/master/symbols/web/{n}/materialsymbolsrounded/{n}{fill}_24px.svg"
        try:
            svg = urllib.request.urlopen(url, timeout=30).read().decode()
            # A few repo files are still the old 24-unit drawings (auto_awesome, insights): icon() needs the 960 grid.
            if 'viewBox="0 -960 960 960"' not in svg:
                svg = urllib.request.urlopen(f"https://fonts.gstatic.com/s/i/short-term/release/materialsymbolsrounded/{n}/{'fill1' if fill else 'default'}/24px.svg", timeout=30).read().decode()
        except Exception as e:
            if fill: continue
            print("missing", n, e, file=sys.stderr); continue
        d = " ".join(re.findall(r'\sd="([^"]+)"', svg))
        key = re.sub(r'_([a-z0-9])', lambda m: m.group(1).upper(), n) + ("Filled" if fill else "")
        out.append((key, d))
body = "\n".join(f'    val {k} by lazy {{ icon("{d}") }}' for k, d in out)
kt = f'''// GENERATED by tools/gen-icons.py from Material Symbols Rounded (Apache-2.0). Do not edit.
package app.buddyverse.design

import androidx.compose.ui.graphics.SolidColor
import androidx.compose.ui.graphics.vector.ImageVector
import androidx.compose.ui.graphics.vector.addPathNodes
import androidx.compose.ui.unit.dp

private fun icon(d: String): ImageVector = ImageVector.Builder(defaultWidth = 24.dp, defaultHeight = 24.dp, viewportWidth = 960f, viewportHeight = 960f)
    .addGroup(translationY = 960f).addPath(addPathNodes(d), fill = SolidColor(androidx.compose.ui.graphics.Color.Black)).clearGroup().build()

object Icons {{
{body}
}}
'''
dest = root / "shared/src/commonMain/kotlin/app/buddyverse/design/Icons.kt"
dest.parent.mkdir(parents=True, exist_ok=True)
dest.write_text(kt, encoding="utf-8")
print("icons:", len(out))
