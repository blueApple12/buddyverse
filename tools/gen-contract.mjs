// Generates Kotlin models from Hermes's OpenRPC wire contract (docs/contract/gateway-contract.openrpc.json).
//   node tools/gen-contract.mjs
// Output: shared/src/commonMain/kotlin/app/buddyverse/core/contract/HermesContract.kt
// Every field is optional (null / empty default) so a newer gateway never breaks decoding; unknown keys are ignored by the Json config.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const rpc = JSON.parse(readFileSync(join(root, 'docs/contract/gateway-contract.openrpc.json'), 'utf8'))
const schemas = rpc.components.schemas
const roots = [
  // turn events
  'MessageDeltaPayload', 'StreamDeltaPayload', 'ToolStartPayload', 'ToolCompletePayload', 'ToolGeneratingPayload',
  'ToolProgressPayload', 'TodoUpdatedPayload', 'MessageCompletePayload', 'MessageInterimPayload', 'SubagentEventPayload',
  'StatusUpdatePayload', 'ErrorPayload', 'RequestCancelPayload', 'NotificationShowPayload', 'SideAgentCompletePayload',
  'SessionUsagePayload', 'SessionReclaimedPayload',
  // canonical session authority
  'CanonicalPendingPrompt', 'CanonicalPendingAdmission', 'CanonicalSnapshot', 'CanonicalListResult', 'SessionActiveListResult',
  'CanonicalProfilesResult', 'CanonicalCorrectionAck', 'CanonicalSessionHandle', 'PromptResponseResult', 'CanonicalEventsResult',
  'AdmissionStatus',
  // discovery
  'CommandsCatalogResult', 'CompleteSlashResult',
  // server requests
  'ClarifyRequestParams', 'SecretRequestParams', 'SudoRequestParams',
]

const out = new Map()
const refName = r => r.split('/').pop()
const camel = s => s.replace(/[^A-Za-z0-9_]/g, '_').replace(/_+([a-zA-Z0-9])/g, (_, c) => c.toUpperCase()).replace(/^[A-Z]/, c => c.toLowerCase())
const KW = new Set(['object', 'class', 'fun', 'val', 'var', 'when', 'in', 'is', 'as', 'do', 'if', 'else', 'for', 'while', 'return', 'null', 'true', 'false', 'package', 'import', 'interface', 'typealias', 'this', 'super', 'throw', 'try'])
const isClass = s => s && s.type === 'object' && s.properties && Object.keys(s.properties).length > 0

function kt(s) {
  if (!s || Object.keys(s).length === 0) return 'JsonElement'
  if (s.$ref) {
    const n = refName(s.$ref), t = schemas[n]
    if (isClass(t)) { want(n); return n }
    return kt({ ...t, title: undefined })
  }
  if (s.anyOf || s.oneOf) {
    const opts = (s.anyOf || s.oneOf).filter(o => o.type !== 'null')
    if (opts.length === 1) return kt(opts[0])
    return 'JsonElement'
  }
  if (s.enum) return 'String'
  switch (s.type) {
    case 'string': return 'String'
    case 'integer': return 'Long'
    case 'number': return 'Double'
    case 'boolean': return 'Boolean'
    case 'array': return `List<${s.items ? kt(s.items) : 'JsonElement'}>`
    case 'object': return s.properties ? 'JsonObject' : 'JsonObject'
    default: return 'JsonElement'
  }
}
function want(n) { if (!out.has(n)) { out.set(n, null); out.set(n, emit(n)) } }
function emit(n) {
  const s = schemas[n]
  const fields = Object.entries(s.properties).map(([k, p]) => {
    const t = kt(p)
    let name = camel(k); if (KW.has(name)) name = `${name}_`
    const def = t.startsWith('List<') ? `${t} = emptyList()` : `${t}? = null`
    return `    @SerialName("${k}") val ${name}: ${def},`
  })
  const doc = (s.description || '').split('\n')[0].replace(/\*\//g, '* /').replace(/``/g, '`').trim()
  return `${doc ? `/** ${doc} */\n` : ''}@Serializable\ndata class ${n}(\n${fields.join('\n')}\n)`
}
for (const r of roots) { if (!isClass(schemas[r])) throw new Error(`not an object schema: ${r}`); want(r) }

const names = list => [...new Set(list.map(m => m.name))].sort()
const methods = names([...rpc.methods, ...(rpc['x-canonical-methods'] || [])])
const events = names(rpc['x-notifications'] || [])
const requests = names(rpc['x-server-requests'] || [])
const strList = a => a.map(x => `        "${x}",`).join('\n')

const file = `// GENERATED by tools/gen-contract.mjs from docs/contract/gateway-contract.openrpc.json. Do not edit.
@file:Suppress("unused")

package app.buddyverse.core.contract

import kotlinx.serialization.SerialName
import kotlinx.serialization.Serializable
import kotlinx.serialization.json.JsonElement
import kotlinx.serialization.json.JsonObject

/** Every JSON-RPC method, notification and server request named by the wire contract. */
object HermesWire {
    val methods: List<String> = listOf(
${strList(methods)}
    )
    val events: List<String> = listOf(
${strList(events)}
    )
    val serverRequests: List<String> = listOf(
${strList(requests)}
    )
    /** Method families: the first dot-separated segment. */
    val families: Set<String> get() = methods.map { it.substringBefore('.') }.toSet()
}

${[...out.values()].join('\n\n')}
`
const dest = join(root, 'shared/src/commonMain/kotlin/app/buddyverse/core/contract/HermesContract.kt')
mkdirSync(dirname(dest), { recursive: true })
writeFileSync(dest, file)
console.log(`wrote ${out.size} classes, ${methods.length} methods, ${events.length} events, ${requests.length} server requests`)
